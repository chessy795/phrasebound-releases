  const word = /[\p{L}\p{M}\p{N}_]/u;
  const normal = value => String(value || '').normalize('NFC').toLowerCase().replace(/[\u2018\u2019]/g, "'").replace(/\s+/g, ' ').trim();
  const grouped = new Map();
  for (const entry of entries) {
    if (!grouped.has(entry.lang)) grouped.set(entry.lang, []);
    grouped.get(entry.lang).push({entry, forms:entry.forms.map(normal)});
  }
  function find(lang, selection, context = '') {
    const code = String(lang || '').toLowerCase().split('-')[0];
    const list = grouped.get(code === 'fil' ? 'tl' : code);
    if (!list) return [];
    const selected = normal(selection);
    const line = normal(context) || selected;
    if (!selected) return [];
    const entire = selected === line;
    const selectedAt = line.indexOf(selected);
    const spaced = !['zh','yue','ja','ko'].includes(code);
    const unique = selectedAt >= 0 && line.indexOf(selected, selectedAt + 1) < 0 &&
      (!spaced || (!word.test(line[selectedAt-1] || '') && !word.test(line[selectedAt+selected.length] || '')));
    return list.filter(({forms}) => forms.some(form => {
      if (selected === form) return true;
      let from = 0;
      while (from < line.length) {
        const at = line.indexOf(form, from);
        if (at < 0) break;
        from = at + form.length;
        if (spaced &&
            (word.test(line[at-1] || '') || word.test(line[from] || ''))) continue;
        if (entire || (unique && selectedAt < from && selectedAt + selected.length > at)) return true;
      }
      return false;
    })).map(item => item.entry);
  }

  function append(parent, lang, selection, context) {
    if (!parent) return;
    const doc = parent.ownerDocument;
    for (const e of find(lang, selection, context)) {
      const panel = doc.createElement('details');
      panel.className = 'ss-literary-source';
      const el = (tag, value) => {
        const node = doc.createElement(tag);
        node.textContent = value;
        panel.appendChild(node);
        return node;
      };
      el('summary', (e.lang === 'zh' || e.lang === 'yue' ? '出處與用典' : 'Literary source') + ' · ' + e.forms[0]);
      el('small', e.kind);
      el('p', e.meaning);
      el('p', e.note);
      const link = (label, url) => {
        const a = el('a', label);
        a.href = url;
        a.target = '_blank';
        a.rel = 'noopener noreferrer';
      };
      link(e.book,e.url);
      if (e.modern) link(e.modern.book, e.modern.url);
      if (e.earlier) {
        el('p', e.earlier.note);
        link(e.earlier.book,e.earlier.url);
      }
      el('p', (e.lang === 'zh' || e.lang === 'yue' ? '自擬例句 · ' : 'Original example · ') + e.example);
      panel.addEventListener('click', ev => ev.stopPropagation());
      parent.appendChild(panel);
    }
  }
  globalThis.SS_LITERARY = {find, append};
